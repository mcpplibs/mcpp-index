int failures = 0;

void check(bool ok, const char* what)
{
    std::printf("%-64s %s\n", what, ok ? "ok" : "FAILED");
    if (!ok) ++failures;
}

// The FLAC fixture's source: a triangle wave per channel (periods 400 and 500)
// plus 4 bits of noise from a 32-bit LCG, interleaved.
std::vector<drflac_int16> flac_signal(unsigned frames, unsigned channels)
{
    std::vector<drflac_int16> out;
    std::uint32_t x = 12345;
    for (unsigned n = 0; n < frames; ++n) {
        for (unsigned c = 0; c < channels; ++c) {
            x = x * 1664525u + 1013904223u;
            int noise = int((x >> 16) & 15) - 8;
            int p = 400 + 100 * int(c), t = int(n) % p;
            int tri = t < p / 2 ? (t * 4 * 8000) / p - 8000 : 24000 - (t * 4 * 8000) / p;
            out.push_back(drflac_int16(tri + noise));
        }
    }
    return out;
}

// Goertzel power of `hz` in a mono signal.
double power(const std::vector<float>& s, double hz, double rate)
{
    const double k = 2.0 * std::cos(2.0 * 3.14159265358979323846 * hz / rate);
    double a = 0, b = 0;
    for (float v : s) { double y = v + k * a - b; b = a; a = y; }
    return a * a + b * b - k * a * b;
}

void wav_round_trip(drwav_container container, const char* label)
{
    const unsigned frames = 1000;
    std::vector<drwav_int16> pcm(frames * 2);
    for (unsigned i = 0; i < pcm.size(); ++i) pcm[i] = drwav_int16((int(i) * 131) % 65536 - 32768);

    drwav_data_format fmt{};
    fmt.container = container;
    fmt.format = DR_WAVE_FORMAT_PCM;
    fmt.channels = 2;
    fmt.sampleRate = 48000;
    fmt.bitsPerSample = 16;
    void* data = nullptr;
    size_t size = 0;
    drwav w;
    char what[96];
    std::snprintf(what, sizeof what, "%s: drwav_init_memory_write", label);
    check(drwav_init_memory_write(&w, &data, &size, &fmt, nullptr) == DRWAV_TRUE, what);
    std::snprintf(what, sizeof what, "%s: drwav_write_pcm_frames writes all frames", label);
    check(drwav_write_pcm_frames(&w, frames, pcm.data()) == frames, what);
    drwav_uninit(&w);

    drwav r;
    std::snprintf(what, sizeof what, "%s: drwav_init_memory reads it back", label);
    check(drwav_init_memory(&r, data, size, nullptr) == DRWAV_TRUE, what);
    std::snprintf(what, sizeof what, "%s: 2 channels, 48000 Hz, 16 bits, 1000 frames", label);
    check(r.channels == 2 && r.sampleRate == 48000 && r.bitsPerSample == 16 && r.totalPCMFrameCount == frames &&
              r.container == container && drwav_fmt_get_format(&r.fmt) == DR_WAVE_FORMAT_PCM, what);
    std::vector<drwav_int16> back(pcm.size());
    std::snprintf(what, sizeof what, "%s: PCM16 sample-exact", label);
    check(drwav_read_pcm_frames_s16(&r, frames, back.data()) == frames && back == pcm, what);
    std::vector<float> f(pcm.size());
    drwav_seek_to_pcm_frame(&r, 0);
    bool exact = drwav_read_pcm_frames_f32(&r, frames, f.data()) == frames;
    for (size_t i = 0; exact && i < f.size(); ++i) exact = f[i] == float(pcm[i]) / 32768.0f;
    std::snprintf(what, sizeof what, "%s: read as f32, each sample s / 32768", label);
    check(exact, what);
    drwav_uninit(&r);
    drwav_free(data, nullptr);
}

void wav_float_and_mulaw()
{
    // IEEE float, bit-exact.
    std::vector<float> f(512);
    for (unsigned i = 0; i < f.size(); ++i) f[i] = float(std::sin(i * 0.05)) * 0.75f;
    drwav_data_format fmt{drwav_container_riff, DR_WAVE_FORMAT_IEEE_FLOAT, 1, 44100, 32};
    void* data = nullptr;
    size_t size = 0;
    drwav w;
    check(drwav_init_memory_write(&w, &data, &size, &fmt, nullptr) == DRWAV_TRUE &&
              drwav_write_pcm_frames(&w, f.size(), f.data()) == f.size(), "IEEE float WAV written");
    drwav_uninit(&w);
    drwav r;
    std::vector<float> back(f.size());
    check(drwav_init_memory(&r, data, size, nullptr) == DRWAV_TRUE &&
              drwav_fmt_get_format(&r.fmt) == DR_WAVE_FORMAT_IEEE_FLOAT &&
              drwav_read_pcm_frames_f32(&r, f.size(), back.data()) == f.size() &&
              std::memcmp(back.data(), f.data(), f.size() * sizeof(float)) == 0,
          "IEEE float WAV read back bit-exact");
    drwav_uninit(&r);
    drwav_free(data, nullptr);

    // mu-law: every code, decoded through the reader and through the table.
    std::vector<drwav_uint8> codes(256);
    for (unsigned i = 0; i < 256; ++i) codes[i] = drwav_uint8(i);
    drwav_data_format mu{drwav_container_riff, DR_WAVE_FORMAT_MULAW, 1, 8000, 8};
    data = nullptr;
    size = 0;
    check(drwav_init_memory_write(&w, &data, &size, &mu, nullptr) == DRWAV_TRUE &&
              drwav_write_pcm_frames(&w, 256, codes.data()) == 256, "mu-law WAV written (all 256 codes)");
    drwav_uninit(&w);
    std::vector<drwav_int16> viaReader(256), viaTable(256);
    drwav_mulaw_to_s16(viaTable.data(), codes.data(), 256);
    check(drwav_init_memory(&r, data, size, nullptr) == DRWAV_TRUE &&
              drwav_read_pcm_frames_s16(&r, 256, viaReader.data()) == 256 && viaReader == viaTable &&
              viaTable[0] == -32124 && viaTable[255] == 0,
          "mu-law WAV decoded by the reader equals drwav_mulaw_to_s16");
    drwav_uninit(&r);
    drwav_free(data, nullptr);
}

struct FlacMeta {
    drflac_uint8 md5[16]{};
    bool streaminfo = false;
    char vendor[32]{};
};

void on_flac_meta(void* user, drflac_metadata* m)
{
    auto* meta = static_cast<FlacMeta*>(user);
    if (m->type == DRFLAC_METADATA_BLOCK_TYPE_STREAMINFO) {
        std::memcpy(meta->md5, m->data.streaminfo.md5, 16);
        meta->streaminfo = true;
    } else if (m->type == DRFLAC_METADATA_BLOCK_TYPE_VORBIS_COMMENT) {
        unsigned n = m->data.vorbis_comment.vendorLength < 31 ? m->data.vorbis_comment.vendorLength : 31;
        std::memcpy(meta->vendor, m->data.vorbis_comment.vendor, n);
    }
}

void flac()
{
    static const drflac_uint8 md5[16] = {0x29, 0x02, 0x2c, 0x35, 0x13, 0xe9, 0xa6, 0xfe,
                                          0xa7, 0x6a, 0x96, 0x0f, 0xd2, 0x14, 0x70, 0xc2};
    FlacMeta meta;
    drflac* f = drflac_open_memory_with_metadata(kToneFlac, sizeof kToneFlac, on_flac_meta, &meta, nullptr);
    check(f != nullptr, "drflac_open_memory_with_metadata");
    if (!f) return;
    check(f->channels == 2 && f->sampleRate == 44100 && f->bitsPerSample == 16 && f->totalPCMFrameCount == 2048,
          "FLAC: 2 channels, 44100 Hz, 16 bits, 2048 frames");
    check(meta.streaminfo && std::memcmp(meta.md5, md5, 16) == 0, "FLAC: STREAMINFO MD5 is the source signal's");
    check(std::strcmp(meta.vendor, "ffmpeg") == 0, "FLAC: VORBIS_COMMENT vendor string");
    const auto want = flac_signal(2048, 2);
    std::vector<drflac_int16> got(want.size());
    check(drflac_read_pcm_frames_s16(f, 2048, got.data()) == 2048 && got == want,
          "FLAC: decoded sample-exact (lossless)");
    std::vector<drflac_int16> tail(2 * 100);
    check(drflac_seek_to_pcm_frame(f, 1100) && drflac_read_pcm_frames_s16(f, 100, tail.data()) == 100 &&
              std::memcmp(tail.data(), want.data() + 2 * 1100, tail.size() * 2) == 0,
          "FLAC: seek to frame 1100, then sample-exact");
    drflac_close(f);
}

void mp3()
{
    drmp3 m;
    check(drmp3_init_memory(&m, kToneMp3, sizeof kToneMp3, nullptr) == DRMP3_TRUE, "drmp3_init_memory");
    check(m.channels == 1 && m.sampleRate == 22050, "MP3: 1 channel, 22050 Hz");
    const drmp3_uint64 frames = drmp3_get_pcm_frame_count(&m);
    std::printf("  MP3 PCM frames: %llu\n", (unsigned long long)frames);
    check(frames == 4410, "MP3: the LAME tag's gapless length, 4410 frames");
    drmp3_seek_to_pcm_frame(&m, 0);
    std::vector<float> s(frames);
    check(drmp3_read_pcm_frames_f32(&m, frames, s.data()) == frames, "MP3: every frame decoded as f32");
    const double p440 = power(s, 440, 22050), p1000 = power(s, 1000, 22050), p220 = power(s, 220, 22050);
    double peak = 0;
    for (float v : s) peak = std::fmax(peak, std::fabs(v));
    std::printf("  MP3 peak %.3f, power 440 Hz / 1000 Hz = %.1f, / 220 Hz = %.1f\n", peak, p440 / p1000, p440 / p220);
    check(peak > 0.3 && peak < 0.45 && p440 > 1000 * p1000 && p440 > 1000 * p220,
          "MP3: a 440 Hz sine at amplitude 12000 / 32768");
    drmp3_uninit(&m);
}

