// yizhinailong.mcr — prove the public module surface compiles, links and
// behaves. A live HTTP round trip is deliberately out of scope: it would need
// a local server plus the curl runtime, neither of which belongs in an index
// member. What is exercised here is everything that is observable offline —
// the generated version module, the status classifiers, the owned option
// types, and the Response JSON parsing path.

import std;
import mcr;

#ifndef MCR_EXPECT_VERSION
#define MCR_EXPECT_VERSION "0.1.5"
#define MCR_EXPECT_MAJOR 0
#define MCR_EXPECT_MINOR 1
#define MCR_EXPECT_PATCH 5
#endif

int main() {
    // mcr.version is generated by the package's own build.mcpp, read out of
    // its mcpp.toml. Asserting on it proves the build hook ran and the
    // generated module unit reached the library target.
    if (mcr::VERSION != MCR_EXPECT_VERSION) return 1;
    if (mcr::VERSION_MAJOR != MCR_EXPECT_MAJOR || mcr::VERSION_MINOR != MCR_EXPECT_MINOR || mcr::VERSION_PATCH != MCR_EXPECT_PATCH) return 2;

    // Status classification is constexpr and independent of libcurl.
    static_assert(mcr::status::is_informational(100));
    static_assert(mcr::status::is_success(200));
    static_assert(mcr::status::is_redirect(301));
    static_assert(mcr::status::is_client_error(404));
    static_assert(mcr::status::is_server_error(503));
    if (!mcr::status::is_success(mcr::status::HTTP_OK)) return 3;
    if (mcr::status::is_success(mcr::status::HTTP_NOT_FOUND)) return 4;

    // Url and Header are the owned, cpr-shaped option types. Header lookups
    // fold case, which is the property std::map alone would not give.
    mcr::Url const url{ "http://127.0.0.1:8080/echo" };
    if (url.Str() != "http://127.0.0.1:8080/echo") return 5;

    mcr::Header header;
    header["Content-Type"] = "application/json";
    if (header.find("content-type") == header.end()) return 6;
    if (header.at("CONTENT-TYPE") != "application/json") return 7;

#if MCR_EXPECT_MAJOR == 0 && MCR_EXPECT_MINOR < 2
    // The preserved 0.1 API owns JSON serialization and parsing.
    mcr::Json const value{ { "name", "Alice" }, { "enabled", true } };
    mcr::JsonBody const body{ value };
    if (mcr::Json::parse(body.Str()) != value) return 8;

    // Response::TryJson reports a parse failure as a diagnostic rather than
    // throwing, while Json() throws and does not check the status code.
    mcr::Response response;
    response.status_code = mcr::status::HTTP_OK;
    response.text        = R"({"answer":42})";
    auto parsed          = response.TryJson();
    if (!parsed) return 9;
    if (parsed->at("answer").get<int>() != 42) return 10;

    response.text = "{ not json";
    auto failed   = response.TryJson();
    if (failed) return 11;
    if (failed.error().message.empty()) return 12;

    bool threw{ false };
    try {
        (void)response.Json();
    } catch (mcr::Json::exception const&) {
        threw = true;
    }
    if (!threw) return 13;
#else
    // 0.2 deliberately removes the JSON dependency: body and response carry
    // bytes verbatim, including embedded nulls. Test the replacement contract.
    std::string const bytes{ "a\0b", 3 };
    mcr::Body const body{ bytes };
    if (body.Str() != bytes) return 8;

    mcr::Response response;
    response.status_code = mcr::status::HTTP_OK;
    response.text = bytes;
    if (response.text != bytes || response.error) return 9;

    // Invalid local input must produce a typed error, without a network call.
    auto invalid = mcr::Response::FromCurl(nullptr, "", "");
    if (invalid) return 10;
    if (invalid.error().code != mcr::ErrorCode::BAD_FUNCTION_ARGUMENT) return 11;
    if (invalid.error().message.empty()) return 12;

    mcr::options::AcceptEncoding const encodings{ std::string{}, std::string{"gzip"} };
    auto const encoding = encodings.GetString();
    if (encoding != ", gzip" && encoding != "gzip, ") return 13;
    mcr::options::MultiRange const ranges{mcr::options::Range{0, 1}, mcr::options::Range{2, 3}};
    if (ranges.Str() != "0-1, 2-3") return 14;
    if (!mcr::options::MultiRange{}.Str().empty()) return 15;
#endif

    return 0;
}
