// FLAC, built bit by bit: STREAMINFO, then frames of 256 samples whose two
// channels are CONSTANT subframes.
struct Bits {
    std::vector<std::uint8_t> bytes;
    int used = 8;
    void put(std::uint64_t value, int n) {
        while (n-- > 0) {
            if (used == 8) { bytes.push_back(0); used = 0; }
            bytes.back() |= std::uint8_t(((value >> n) & 1) << (7 - used++));
        }
    }
};

std::uint8_t crc8(std::span<const std::uint8_t> data) {
    std::uint8_t crc = 0;
    for (std::uint8_t b : data) {
        crc ^= b;
        for (int i = 0; i < 8; ++i) crc = std::uint8_t(crc & 0x80 ? (crc << 1) ^ 0x07 : crc << 1);
    }
    return crc;
}

std::uint16_t crc16(std::span<const std::uint8_t> data) {
    std::uint16_t crc = 0;
    for (std::uint8_t b : data) {
        crc ^= std::uint16_t(b << 8);
        for (int i = 0; i < 8; ++i) crc = std::uint16_t(crc & 0x8000 ? (crc << 1) ^ 0x8005 : crc << 1);
    }
    return crc;
}

std::vector<std::uint8_t> flac(const std::vector<std::array<std::int16_t, 2>>& frames) {
    std::vector<std::uint8_t> out = {'f', 'L', 'a', 'C', 0x80, 0, 0, 34};  // the last block: STREAMINFO, 34 bytes
    Bits si;
    si.put(256, 16); si.put(256, 16); si.put(0, 24); si.put(0, 24);
    si.put(44100, 20); si.put(1, 3); si.put(15, 5); si.put(256 * frames.size(), 36);
    si.put(0, 64); si.put(0, 64);  // MD5 unknown: not checked
    out.insert(out.end(), si.bytes.begin(), si.bytes.end());
    for (std::size_t n = 0; n < frames.size(); ++n) {
        Bits f;
        f.put(0x3FFE, 14); f.put(0, 1); f.put(0, 1);  // sync, reserved, fixed block size
        f.put(0b0110, 4); f.put(0b1001, 4);            // block size from the header's end; 44.1 kHz
        f.put(0b0001, 4); f.put(0b100, 3); f.put(0, 1);  // two independent channels; 16 bits
        f.put(n, 8);                                     // frame number (UTF-8 coded, < 128)
        f.put(255, 8);                                   // block size - 1
        f.put(crc8(f.bytes), 8);
        for (std::int16_t v : frames[n]) {
            f.put(0, 8);                                 // CONSTANT subframe, no wasted bits
            f.put(std::uint16_t(v), 16);
        }
        f.put(crc16(f.bytes), 16);
        out.insert(out.end(), f.bytes.begin(), f.bytes.end());
    }
    return out;
}

double power(std::span<const float> s, double hz, double rate) {  // Goertzel
    const double k = 2.0 * std::cos(2.0 * std::numbers::pi * hz / rate);
    double a = 0, b = 0;
    for (float v : s) {
        double y = v + k * a - b;
        b = a;
        a = y;
    }
    return a * a + b * b - k * a * b;
}

