int main() {
    if (std::string_view(drwav_version_string()) != "0.14.5" || std::string_view(drflac_version_string()) != "0.13.3" ||
        std::string_view(drmp3_version_string()) != "0.7.3")
        return 1;

    // dr_wav: PCM16 stereo in memory, read back.
    std::vector<drwav_int16> pcm(2 * 500);
    for (std::size_t i = 0; i < pcm.size(); ++i) pcm[i] = drwav_int16(int(i * 97 % 60000) - 30000);
    drwav_data_format format{drwav_container_riff, DR_WAVE_FORMAT_PCM, 2, 48000, 16};
    void* data = nullptr;
    std::size_t size = 0;
    drwav w;
    if (!drwav_init_memory_write(&w, &data, &size, &format, nullptr) || drwav_write_pcm_frames(&w, 500, pcm.data()) != 500) return 2;
    if (drwav_uninit(&w) != DRWAV_SUCCESS) return 3;
    drwav r;
    if (!drwav_init_memory(&r, data, size, nullptr) || r.totalPCMFrameCount != 500 || drwav_fmt_get_format(&r.fmt) != DR_WAVE_FORMAT_PCM) return 4;
    std::vector<drwav_int16> back(pcm.size());
    if (drwav_read_pcm_frames_s16(&r, 500, back.data()) != 500 || back != pcm) return 5;
    drwav_uninit(&r);
    drwav_free(data, nullptr);

    // dr_flac: two frames, then a seek into the second.
    const auto stream = flac({{{1000, -1000}}, {{-5, 7}}});
    drflac* f = drflac_open_memory(stream.data(), stream.size(), nullptr);
    if (f == nullptr || f->channels != 2 || f->sampleRate != 44100 || f->totalPCMFrameCount != 512) return 6;
    std::vector<drflac_int16> s(2 * 512);
    if (drflac_read_pcm_frames_s16(f, 512, s.data()) != 512) return 7;
    if (s[0] != 1000 || s[1] != -1000 || s[2 * 255 + 1] != -1000 || s[2 * 256] != -5 || s[2 * 511 + 1] != 7) return 8;
    drflac_int16 two[2];
    if (!drflac_seek_to_pcm_frame(f, 300) || drflac_read_pcm_frames_s16(f, 1, two) != 1 || two[0] != -5 || two[1] != 7) return 9;
    drflac_close(f);

    // dr_mp3: the gapless length and the tone.
    drmp3 m;
    if (!drmp3_init_memory(&m, kToneMp3, sizeof kToneMp3, nullptr) || m.channels != 1 || m.sampleRate != 22050) return 10;
    if (drmp3_get_pcm_frame_count(&m) != 4410 || !drmp3_seek_to_pcm_frame(&m, 0)) return 11;
    std::vector<float> tone(4410);
    if (drmp3_read_pcm_frames_f32(&m, 4410, tone.data()) != 4410) return 12;
    drmp3_uninit(&m);
    if (!(power(tone, 440, 22050) > 1000 * power(tone, 1000, 22050))) return 13;

    static_assert(DRMP3_MAX_PCM_FRAMES_PER_MP3_FRAME == 1152 && DRFLAC_METADATA_BLOCK_TYPE_STREAMINFO == 0);
    std::println("dr_libs-audio: dr_wav {}, dr_flac {}, dr_mp3 {}: ok", drwav_version_string(), drflac_version_string(),
                 drmp3_version_string());
    return 0;
}
